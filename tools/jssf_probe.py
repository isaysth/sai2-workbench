TAG_JSSF = b"jssf"
TAG_DPCM = b"dpcm"


def read_canvas_entries(data: bytes):
    """解析 SAI-CANVAS-TYPE0 块表，返回 (header, entries)。

    header: dict(width,height,table_count,canvas_bg_flags)
    entries: [(tag, layer_id, offset, size)]
    """
    if data[:16] != b"SAI-CANVAS-TYPE0":
        raise ValueError("不是 SAI2 画布文件")
    _flags0, bg_flags, _f2, _f3 = data[16:20]
    width, height, _res, table_count = struct.unpack_from("<IIII", data, 20)
    entries = []
    off = 64
    for _ in range(table_count):
        tag = data[off:off + 4]
        layer_id, pos, _pad = struct.unpack_from("<III", data, off + 4)
        entries.append([tag, layer_id, pos, 0])
        off += 16
    for i, ent in enumerate(entries):
        end = entries[i + 1][2] if i + 1 < len(entries) else len(data)
        ent[3] = end - ent[2]
    header = {
        "width": width,
        "height": height,
        "table_count": table_count,
        "canvas_bg_flags": bg_flags,
    }
    return header, entries


def jssf_to_jpeg(blob: bytes) -> tuple[bytes, int, int]:
    """把 thum 块(jssf) 还原成标准 JPEG 字节流。"""
    _w32, _h32 = struct.unpack_from("<II", blob, 0)
    if blob[8:12] != TAG_JSSF:
        raise ValueError(f"不是 jssf 块: {blob[8:12]!r}")
    jw, jh, ch = struct.unpack_from("<HHH", blob, 12)
    p = 18

    q_luma = blob[p:p + 64]
    p += 64
    q_chroma = None
    if ch > 1:
        q_chroma = blob[p:p + 64]
        p += 64

    out = bytearray(b"\xff\xd8")  # SOI

    # DQT
    body = b"\x00" + q_luma
    if ch > 1:
        body += b"\x01" + q_chroma
    out += b"\xff\xdb" + struct.pack(">H", 2 + len(body)) + body

    # DHT
    dht = LUT0 + LUT1
    if ch > 1:
        dht += LUT2 + LUT3
    out += b"\xff\xc4" + struct.pack(">H", 2 + len(dht)) + dht

    # SOF0
    sof = struct.pack(">BHHB", 8, jh, jw, ch)
    for ci in range(ch):
        sof += bytes([ci + 1, 0x11, 0 if ci == 0 else 1])
    out += b"\xff\xc0" + struct.pack(">H", 2 + len(sof)) + sof

    # DRI：每行一个 restart
    out += b"\xff\xdd" + struct.pack(">HH", 4, (jw + 7) // 8)

    # SOS
    sos = bytes([ch])
    for ci in range(ch):
        sos += bytes([ci + 1, 0x00 if ci == 0 else 0x11])
    sos += b"\x00\x3f\x00"
    out += b"\xff\xda" + struct.pack(">H", 2 + len(sos)) + sos

    # 逐行：u16 长度 + 熵数据 + RST 标记
    rows = (jh + 7) // 8
    for r in range(rows):
        if p + 2 > len(blob):
            raise ValueError(f"第 {r} 行越界，已消耗 {p}/{len(blob)}")
        size = struct.unpack_from("<H", blob, p)[0]
        p += 2
        if p + size > len(blob):
            raise ValueError(f"第 {r} 行数据越界: size={size} 剩余={len(blob)-p}")
        out += blob[p:p + size]
        p += size
        if r < rows - 1:
            out += b"\xff" + bytes([0xD0 | (r & 0b111)])

    out += b"\xff\xd9"  # EOI
    return bytes(out), jw, jh


def decode_file(path: Path) -> None:
    data = path.read_bytes()
    header, entries = read_canvas_entries(data)
    print(f"\n=== {path.name} {header['width']}x{header['height']} "
          f"bg_flags={header['canvas_bg_flags']} 块={len(entries)} ===")
    tags = [e[0].decode("latin1") for e in entries]
    print("  块类型:", " ".join(sorted(set(tags))))

    for tag, _lid, pos, size in entries:
        if tag == b"thum":
            blob = data[pos:pos + size]
            print(f"  thum 块 {size} 字节，头部 {blob[:20].hex(' ')}")
            try:
                jpeg, w, h = jssf_to_jpeg(blob)
                print(f"  重建 JPEG: {len(jpeg)} 字节, {w}x{h}")
                img = Image.open(io.BytesIO(jpeg))
                img.load()
                print(f"  解码成功: {img.size} {img.mode}")
                outp = path.with_suffix(".thumb.png")
                img.convert("RGB").save(outp)
                print(f"  已保存 -> {outp.name}")
            except Exception as exc:  # noqa: BLE001
                print(f"  失败: {type(exc).__name__}: {exc}")
            return
    print("  没有 thum 块（小画布走 intg/dpcm 路径）")


