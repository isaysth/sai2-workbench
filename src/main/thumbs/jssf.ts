const TAG_JSSF = 'jssf'

export interface JssfResult {
  jpeg: Uint8Array
  width: number
  height: number
  channels: number
}

/** 大端 u16 写入 */
function be16(out: number[], v: number): void {
  out.push((v >> 8) & 0xff, v & 0xff)
}

function pushSegment(out: number[], marker: number, body: Uint8Array | number[]): void {
  out.push(0xff, marker)
  be16(out, body.length + 2)
  for (let i = 0; i < body.length; i++) out.push(body[i]!)
}

/**
 * 重建 JPEG。抛 `Sai2Error` 表示数据不完整/不符合预期，由调度层降级，
 * 不要在这里吞掉错误 —— 上层要靠它区分"这张图本来就没有预览"和"代码写错了"。
 */
export function jssfToJpeg(blob: Uint8Array): JssfResult {
  const view = new DataView(blob.buffer, blob.byteOffset, blob.byteLength)
  if (blob.length < 18) throw new Sai2Error('jssf 头部不完整')

  const tag = String.fromCharCode(blob[8]!, blob[9]!, blob[10]!, blob[11]!)
  if (tag !== TAG_JSSF) throw new Sai2Error(`不是 jssf 块：${tag}`)

  const jw = view.getUint16(12, true)
  const jh = view.getUint16(14, true)
  const ch = view.getUint16(16, true)
  if (jw === 0 || jh === 0) throw new Sai2Error(`jssf 尺寸异常：${jw}×${jh}`)
  if (ch !== 1 && ch !== 3) throw new Sai2Error(`jssf 通道数异常：${ch}`)

  let p = 18
  if (p + 64 > blob.length) throw new Sai2Error('缺少亮度量化表')
  const qLuma = blob.subarray(p, p + 64)
  p += 64

  let qChroma: Uint8Array | null = null
  if (ch > 1) {
    if (p + 64 > blob.length) throw new Sai2Error('缺少色度量化表')
    qChroma = blob.subarray(p, p + 64)
    p += 64
  }

  const out: number[] = [0xff, 0xd8] // SOI

  // DQT
  const dqt: number[] = [0x00, ...qLuma]
  if (qChroma) dqt.push(0x01, ...qChroma)
  pushSegment(out, 0xdb, dqt)

  // DHT
  const dht: number[] = [...LUT0, ...LUT1]
  if (ch > 1) dht.push(...LUT2, ...LUT3)
  pushSegment(out, 0xc4, dht)

  // SOF0
  const sof: number[] = [8]
  be16(sof, jh)
  be16(sof, jw)
  sof.push(ch)
  for (let ci = 0; ci < ch; ci++) sof.push(ci + 1, 0x11, ci === 0 ? 0 : 1)
  pushSegment(out, 0xc0, sof)

  // DRI：每行一个 restart interval
  const restartInterval = (jw + 7) >> 3
  pushSegment(out, 0xdd, [(restartInterval >> 8) & 0xff, restartInterval & 0xff])

  // SOS
  const sos: number[] = [ch]
  for (let ci = 0; ci < ch; ci++) sos.push(ci + 1, ci === 0 ? 0x00 : 0x11)
  sos.push(0x00, 0x3f, 0x00)
  pushSegment(out, 0xda, sos)

  // 逐行：u16 长度 + 熵数据 + RSTn
  const rows = (jh + 7) >> 3
  for (let r = 0; r < rows; r++) {
    if (p + 2 > blob.length) throw new Sai2Error(`第 ${r} 行越界（已消耗 ${p}/${blob.length}）`)
    const size = view.getUint16(p, true)
    p += 2
    if (p + size > blob.length) {
      throw new Sai2Error(`第 ${r} 行数据越界：size=${size} 剩余=${blob.length - p}`)
    }
    for (let i = 0; i < size; i++) out.push(blob[p + i]!)
    p += size
    if (r < rows - 1) out.push(0xff, 0xd0 | (r & 7))
  }

  out.push(0xff, 0xd9) // EOI
  return { jpeg: Uint8Array.from(out), width: jw, height: jh, channels: ch }
}
