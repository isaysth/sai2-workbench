/**
 * `jssf` → 标准 JPEG 字节流。
 *
 * `jssf` 本质是「剥掉了所有标记的 JPEG」：只留下量化表、逐行的熵编码数据，
 * 段结构（SOI/DQT/DHT/SOF/DRI/SOS/EOI）和 Huffman 表全部由解码方补回。
 * SAI 这么存是为了让缩略图块尽量小 —— 一张 375×500 的预览只占 67KB。
 *
 * 实现**逐段对照 `tools/jssf_probe.py`**（该脚本已用真实稿件验证过）：
 * Huffman 表是照抄的字节常量，不要"顺手优化"成重新构造 —— 差一个字节就花屏，
 * 而且是那种"大部分图正常、某些图下半截发绿"的难查故障。
 *
 * 关键参数：
 *   DRI = ceil(w/8)      一行一个 restart interval
 *   采样因子 0x11        各通道都是 1×1（jssf 不做色度下采样）
 *   RSTn 插在行与行之间，n = 行号 & 7
 */

